static uint8_t xt(uint8_t x) { return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1b : 0)); }
static void aes128_blk(const uint8_t *key, uint8_t s[16])
{
    uint8_t w[176]; uint8_t rc = 1;
    memcpy(w, key, 16);
    for (int i = 4; i < 44; i++)
    {
        uint8_t t[4]; memcpy(t, w + (i - 1) * 4, 4);
        if (i % 4 == 0) { uint8_t u = t[0]; t[0] = (uint8_t)(SB[t[1]] ^ rc); t[1] = SB[t[2]]; t[2] = SB[t[3]]; t[3] = SB[u]; rc = xt(rc); }
        for (int j = 0; j < 4; j++) { w[i * 4 + j] = (uint8_t)(w[(i - 4) * 4 + j] ^ t[j]); }
    }
    for (int i = 0; i < 16; i++) { s[i] ^= w[i]; }
    for (int r = 1; r <= 10; r++)
    {
        uint8_t t[16];
        for (int i = 0; i < 16; i++) { t[i] = SB[s[i]]; }
        for (int i = 0; i < 16; i++) { s[i] = t[(i + 4 * (i % 4)) % 16]; }
        if (r != 10)
        {
            for (int c = 0; c < 4; c++)
            {
                uint8_t *a = s + 4 * c; uint8_t a0 = a[0], a1 = a[1], a2 = a[2], a3 = a[3];
                uint8_t tt = (uint8_t)(a0 ^ a1 ^ a2 ^ a3);
                a[0] = (uint8_t)(a0 ^ tt ^ xt((uint8_t)(a0 ^ a1))); a[1] = (uint8_t)(a1 ^ tt ^ xt((uint8_t)(a1 ^ a2)));
                a[2] = (uint8_t)(a2 ^ tt ^ xt((uint8_t)(a2 ^ a3))); a[3] = (uint8_t)(a3 ^ tt ^ xt((uint8_t)(a3 ^ a0)));
            }
        }
        for (int i = 0; i < 16; i++) { s[i] ^= w[r * 16 + i]; }
    }
}
static void aes256_blk(const uint8_t *key, uint8_t block[16]) { aes256_ecb_encrypt(key, block); }

